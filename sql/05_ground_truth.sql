USE DATABASE AI_DATA_CORRECTNESS;
USE SCHEMA EXPERIMENT;

-- Overall total: 2500
SELECT SUM(EXPENSE_AMOUNT) AS TOTAL_EXPENSE
FROM EXPENSE_FACT;

-- Historical attribution:
-- Finance 900, Operations 1300, Sales 300
SELECT
    e.DEPARTMENT,
    SUM(x.EXPENSE_AMOUNT) AS EXPENSE_AMOUNT
FROM EXPENSE_FACT x
JOIN EMPLOYEE_DIM_SCD2 e
    ON x.EMPLOYEE_ID = e.EMPLOYEE_ID
   AND x.EXPENSE_DATE >= e.VALID_FROM
   AND x.EXPENSE_DATE < e.VALID_TO
GROUP BY e.DEPARTMENT
ORDER BY e.DEPARTMENT;

-- Current attribution:
-- Finance 1100, Operations 1400
SELECT
    e.DEPARTMENT,
    SUM(x.EXPENSE_AMOUNT) AS EXPENSE_AMOUNT
FROM EXPENSE_FACT x
JOIN EMPLOYEE_DIM_SCD2 e
    ON x.EMPLOYEE_ID = e.EMPLOYEE_ID
   AND e.IS_CURRENT = TRUE
GROUP BY e.DEPARTMENT
ORDER BY e.DEPARTMENT;

-- Boundary checks:
-- Employee 101, 2026-07-01 -> Operations
-- Employee 103, 2026-04-01 -> Finance
SELECT
    x.EXPENSE_ID,
    x.EMPLOYEE_ID,
    x.EXPENSE_DATE,
    x.EXPENSE_AMOUNT,
    e.DEPARTMENT
FROM EXPENSE_FACT x
JOIN EMPLOYEE_DIM_SCD2 e
    ON x.EMPLOYEE_ID = e.EMPLOYEE_ID
   AND x.EXPENSE_DATE >= e.VALID_FROM
   AND x.EXPENSE_DATE < e.VALID_TO
WHERE x.EXPENSE_ID IN ('X2', 'X6')
ORDER BY x.EXPENSE_ID;
