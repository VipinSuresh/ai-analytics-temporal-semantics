-- Usage by agent
SELECT
    AGENT_NAME,
    COUNT(*) AS REQUESTS,
    SUM(TOKENS) AS TOTAL_TOKENS,
    SUM(TOKEN_CREDITS) AS AI_CREDITS,
    SUM(COALESCE(METADATA:sql_query_credits::FLOAT, 0)) AS SQL_WAREHOUSE_CREDITS,
    MIN(START_TIME) AS FIRST_REQUEST,
    MAX(END_TIME) AS LAST_REQUEST
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AGENT_USAGE_HISTORY
WHERE AGENT_NAME IN (
    'EXPENSE_CURRENT_STATE_AGENT',
    'EXPENSE_TEMPORAL_AGENT',
    'EXPENSE_ENRICHED_AGENT'
)
GROUP BY AGENT_NAME
ORDER BY AGENT_NAME;

-- Overall usage
SELECT
    COUNT(*) AS TOTAL_REQUESTS,
    SUM(TOKENS) AS TOTAL_TOKENS,
    SUM(TOKEN_CREDITS) AS TOTAL_AI_CREDITS,
    SUM(COALESCE(METADATA:sql_query_credits::FLOAT, 0)) AS TOTAL_SQL_WAREHOUSE_CREDITS
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AGENT_USAGE_HISTORY
WHERE AGENT_NAME IN (
    'EXPENSE_CURRENT_STATE_AGENT',
    'EXPENSE_TEMPORAL_AGENT',
    'EXPENSE_ENRICHED_AGENT'
);

-- Example: retrieve agent question/answer events.
-- Replace the agent name as needed.
SELECT
    START_TIMESTAMP AS STARTED_AT,
    RECORD_ATTRIBUTES:"snow.ai.observability.agent.request_id"::STRING AS REQUEST_ID,
    RECORD_ATTRIBUTES:"ai.observability.record_root.input"::STRING AS QUESTION,
    RECORD_ATTRIBUTES:"ai.observability.record_root.output"::STRING AS ANSWER
FROM TABLE(
    SNOWFLAKE.LOCAL.GET_AI_OBSERVABILITY_EVENTS(
        'AI_DATA_CORRECTNESS',
        'EXPERIMENT',
        'EXPENSE_CURRENT_STATE_AGENT',
        'CORTEX AGENT'
    )
)
WHERE RECORD:name = 'AgentV2RequestResponseInfo'
ORDER BY STARTED_AT;
